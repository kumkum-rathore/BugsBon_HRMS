const express = require('express');
const cors = require('cors');
const helmet = require('helmet');
const cookieParser = require('cookie-parser');
const rateLimit = require('express-rate-limit');
const { sendSuccess, sendError } = require('./utils/apiResponse');
const authRoutes = require('./routes/auth.routes');
const branchRoutes = require('./routes/branch.routes');
const employeeRoutes = require('./routes/employee.routes');
const attendanceRoutes = require('./routes/attendance.routes');
const leaveRoutes = require('./routes/leave.routes');
const dashboardRoutes = require('./routes/dashboard.routes');
const departmentRoutes = require('./routes/department.routes');
const roleRoutes = require('./routes/role.routes');
const taskRoutes = require('./routes/task.routes');
const projectRoutes = require('./routes/project.routes');
const salaryRoutes = require('./routes/salary.routes');
const calendarRoutes = require('./routes/calendar.routes');
const notificationRoutes = require('./routes/notification.routes');
const documentRoutes = require('./routes/document.routes');
const accountRoutes = require('./routes/account.routes');
const uploadRoutes = require('./routes/upload.routes');
const notFound = require('./middleware/notFound');
const errorHandler = require('./middleware/errorHandler');
const mongoose = require('mongoose');
const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: process.env.CLIENT_URL || 'http://localhost:5173', credentials: true, methods: ['GET', 'POST', 'PATCH', 'PUT', 'DELETE', 'OPTIONS'], allowedHeaders: ['Content-Type', 'Authorization', 'X-Client-Type'] }));
app.use(express.json({ limit: '1mb' }));
app.use(express.urlencoded({ extended: false, limit: '1mb' }));
app.use(cookieParser());
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 300, standardHeaders: true, legacyHeaders: false, message: { success: false, message: 'Too many requests. Please try again later.', error: { code: 'RATE_LIMIT_EXCEEDED', details: [] } } }));
app.get('/', (req, res) => sendSuccess(res, { message: 'Welcome to Bugsbon HRMS API.', data: { apiVersion: 'v1', healthEndpoint: '/api/v1/health' } }));
app.get('/api/v1/health', (req, res) => {
  const connected = mongoose.connection.readyState === 1;
  return connected ? sendSuccess(res, { message: 'API and database are healthy.', data: { service: 'Bugsbon HRMS API', status: 'healthy', database: 'connected', timestamp: new Date().toISOString() } }) : sendError(res, { statusCode: 503, message: 'API is running but database is unavailable.', code: 'DATABASE_UNAVAILABLE' });
});
app.use('/api/v1/auth', authRoutes);
app.use('/api/v1/dashboard', dashboardRoutes);
app.use('/api/v1/branches', branchRoutes);
app.use('/api/v1/employees', employeeRoutes);
app.use('/api/v1/attendance', attendanceRoutes);
app.use('/api/v1/leaves', leaveRoutes);
app.use('/api/v1/departments', departmentRoutes);
app.use('/api/v1/roles', roleRoutes);
app.use('/api/v1/tasks', taskRoutes);
app.use('/api/v1/projects', projectRoutes);
app.use('/api/v1/salaries', salaryRoutes);
app.use('/api/v1/calendar', calendarRoutes);
app.use('/api/v1/notifications', notificationRoutes);
app.use('/api/v1/documents', documentRoutes);
app.use('/api/v1/account', accountRoutes);
app.use('/api/v1/uploads', uploadRoutes);
app.use(notFound);
app.use(errorHandler);
module.exports = app;
